function blockframe.translate_node(mc_name)
    -- Remove namespace if present for lookup
    if blockframe.mc_translate[mc_name] then
        return blockframe.mc_translate[mc_name]
    end

    -- Basic fallback logic
    local fallback = mc_name:gsub("minecraft:", "mcl_core:")
    
    -- In Minetest/Mineclonia, we check if the node is registered
    if minetest and minetest.registered_nodes and minetest.registered_nodes[fallback] then
        return fallback
    end

    return mc_name
end
